-- Findly initial schema: reports table, row level security, and photo storage.
--
-- Run once against your Supabase project (SQL editor or `supabase db push`).
-- Security model:
--   * Only signed-in (email-verified) users can read reports. Anonymous
--     visitors see nothing.
--   * Users create reports only as themselves and edit/delete only their own.
--   * Column privileges stop clients from writing owner_id, timestamps,
--     is_demo, or changing a report's type after creation.
--   * No personal contact details are stored in this table.

-- ---------------------------------------------------------------------------
-- Types
-- ---------------------------------------------------------------------------

create type public.report_type as enum ('lost', 'found');

create type public.report_status as enum ('active', 'resolved');

create type public.item_category as enum (
  'electronics',
  'bags',
  'keys',
  'wallets_cards',
  'id_documents',
  'clothing',
  'accessories',
  'books_stationery',
  'bottles',
  'other'
);

-- ---------------------------------------------------------------------------
-- Reports
-- ---------------------------------------------------------------------------

create table public.reports (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null default auth.uid()
    references auth.users (id) on delete cascade,
  type public.report_type not null,
  status public.report_status not null default 'active',
  title text not null,
  description text not null,
  category public.item_category not null,
  location text not null,
  event_date date not null,
  photo_path text,
  is_demo boolean not null default false,
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint reports_title_length
    check (title = btrim(title) and char_length(title) between 3 and 80),
  constraint reports_description_length
    check (description = btrim(description)
           and char_length(description) between 10 and 1000),
  constraint reports_location_length
    check (location = btrim(location) and char_length(location) between 2 and 120),
  constraint reports_event_date_floor
    check (event_date >= date '2000-01-01'),
  -- <owner uuid>/<epoch millis>-<8 hex>.<ext>, generated by the app.
  constraint reports_photo_path_format
    check (photo_path is null or photo_path ~
      '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/[0-9]{10,16}-[0-9a-f]{8}\.(jpg|png|webp)$'),
  -- A report may only reference a photo inside its owner's storage folder.
  constraint reports_photo_in_owner_folder
    check (photo_path is null or split_part(photo_path, '/', 1) = owner_id::text),
  constraint reports_resolved_at_matches_status
    check ((status = 'resolved') = (resolved_at is not null))
);

comment on table public.reports is
  'Lost and found reports. Contains no personal contact details.';

create index reports_created_at_idx on public.reports (created_at desc);
create index reports_status_type_idx on public.reports (status, type);
create index reports_owner_id_idx on public.reports (owner_id);
create index reports_photo_path_idx on public.reports (photo_path)
  where photo_path is not null;

-- Maintains updated_at/resolved_at and rejects future event dates.
-- One day of slack covers users whose local date is ahead of UTC.
create function public.reports_before_write()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();

  if tg_op = 'INSERT' or new.event_date is distinct from old.event_date then
    if new.event_date > (now() at time zone 'utc')::date + 1 then
      raise exception 'event_date cannot be in the future'
        using errcode = '23514';
    end if;
  end if;

  if new.status = 'resolved' then
    if tg_op = 'INSERT' or old.status <> 'resolved' then
      new.resolved_at := now();
    end if;
  else
    new.resolved_at := null;
  end if;

  return new;
end;
$$;

create trigger reports_before_write
  before insert or update on public.reports
  for each row execute function public.reports_before_write();

-- Abuse control: at most 20 new reports per user per 24 hours.
create function public.reports_enforce_rate_limit()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  recent_count integer;
begin
  select count(*) into recent_count
  from public.reports
  where owner_id = new.owner_id
    and created_at > now() - interval '24 hours';

  if recent_count >= 20 then
    raise exception 'rate_limit_exceeded: too many reports in 24 hours'
      using errcode = 'P0001';
  end if;
  return new;
end;
$$;

revoke execute on function public.reports_enforce_rate_limit() from public, anon, authenticated;

create trigger reports_enforce_rate_limit
  before insert on public.reports
  for each row execute function public.reports_enforce_rate_limit();

-- Column privileges. Supabase grants everything to anon/authenticated by
-- default, so start from nothing and add back only what the app needs.
revoke all on table public.reports from anon, authenticated;

grant select on table public.reports to authenticated;
grant insert (type, title, description, category, location, event_date, photo_path)
  on table public.reports to authenticated;
grant update (status, title, description, category, location, event_date, photo_path)
  on table public.reports to authenticated;
grant delete on table public.reports to authenticated;

alter table public.reports enable row level security;

create policy "Signed-in users can read reports"
  on public.reports for select
  to authenticated
  using (true);

create policy "Users create reports as themselves"
  on public.reports for insert
  to authenticated
  with check (owner_id = (select auth.uid()) and is_demo = false);

create policy "Owners update their reports"
  on public.reports for update
  to authenticated
  using (owner_id = (select auth.uid()))
  with check (owner_id = (select auth.uid()));

create policy "Owners delete their reports"
  on public.reports for delete
  to authenticated
  using (owner_id = (select auth.uid()));

-- ---------------------------------------------------------------------------
-- Photo storage
-- ---------------------------------------------------------------------------

-- Private bucket: photos are served through short-lived signed URLs to
-- signed-in users only. Size and MIME type are enforced by Storage itself.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'report-photos',
  'report-photos',
  false,
  5242880, -- 5 MB
  array['image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do update
  set public = excluded.public,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

-- Upload only directly into your own folder, only image extensions.
create policy "Users upload photos to their own folder"
  on storage.objects for insert
  to authenticated
  with check (
    bucket_id = 'report-photos'
    and array_length(storage.foldername(name), 1) = 1
    and (storage.foldername(name))[1] = (select auth.uid()::text)
    and lower(storage.extension(name)) in ('jpg', 'png', 'webp')
  );

-- See your own uploads, plus any photo attached to a report (reports are
-- readable by all signed-in users). Orphaned uploads stay private.
create policy "Signed-in users view report photos"
  on storage.objects for select
  to authenticated
  using (
    bucket_id = 'report-photos'
    and (
      (storage.foldername(name))[1] = (select auth.uid()::text)
      or exists (
        select 1 from public.reports r where r.photo_path = objects.name
      )
    )
  );

-- Delete only your own photos. There is deliberately no UPDATE policy, so
-- objects cannot be overwritten or moved.
create policy "Users delete their own photos"
  on storage.objects for delete
  to authenticated
  using (
    bucket_id = 'report-photos'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  );
